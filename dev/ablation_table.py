"""Collect ablation / cost numbers for the report from dev run records.

Reads ~/mp3/work/runs/*/summary.json (train/val official runs scored by dev/eval.py) and the
LLM generation evaluations; writes dev/reports/ablations.md. Test numbers are
not read here (they come from the two frozen test runs only).
"""
import json
import os
from pathlib import Path

WORK = Path(os.environ.get("MP3_WORK", Path.home() / "mp3/work"))
OUT = Path(__file__).resolve().parent / "reports" / "ablations.md"


def run(name):
    s = json.loads((WORK / "runs" / name / "summary.json").read_text())
    g = s["groups"]
    calls = sum(v["calls"] for v in g.values()) / sum(v["n"] for v in g.values())
    return {k: g[k]["correct"] for k in g}, calls, s.get("diff", {})


def row(label, name, base=None):
    got, calls, diff = run(name)
    cells = [f"{got['discovery']}/292", f"{got['holdout']}/188", f"{got['validation']}/120"]
    if base:
        b, _, _ = run(base)
        cells = [f"{c} ({got[k] - b[k]:+d})" for c, k in zip(cells, ("discovery", "holdout", "validation"))]
    return f"| {label} | " + " | ".join(cells) + f" | {calls:.2f} |"


lines = ["# Ablation tables (generated by dev/ablation_table.py)", "",
         "Train is split by schema into discovery (71 DBs, 292 tasks) and holdout (47 DBs, 188 tasks).",
         "All numbers are official three-instance correctness from mp3_sql.score.", "",
         "## A1. Final-stage convention rewrites (no LLM)", "",
         "| configuration | discovery | holdout | validation | mean tool calls |", "|---|---|---|---|---|",
         row("v1 (inherited rule controller)", "v1"),
         row("+ join pruning", "v1-prune", "v1"),
         row("+ join pruning + semi-join (= v2 without LLM)", "v2-nollm", "v1"), "",
         "## A2. LLM proposer (dev adapter trained on discovery only; difference vs v2 without LLM)", "",
         "Discovery numbers are in-sample for the adapter and are shown for completeness only.", "",
         "| configuration | discovery | holdout | validation | mean tool calls |", "|---|---|---|---|---|",
         row("v2 without LLM", "v2-nollm"),
         row("LLM only after v1 finishes (no reserve)", "llm_nm", "v2-nollm"),
         row("reserve K=2, draft-first, static schema filter (chosen)", "llm_nm2", "v2-nollm"),
         row("reserve K=3, draft-first, static schema filter", "llm_nm3", "v2-nollm"), ""]

gen = WORK / "llm" / "gen_eval"
lines += ["## A3. Stand-alone generation quality (greedy, original draft as input)", "",
          "| model | split | parsed | matches public example | correct (3 instances) | rescues a failure of v2 without LLM | harmful* |",
          "|---|---|---|---|---|---|---|"]
for name, label in (("base-validation", "Qwen3-0.6B, no adapter"),
                    ("disc-r16-epoch1-validation", "dev adapter epoch 1"),
                    ("disc-r16-epoch2-validation", "dev adapter epoch 2"),
                    ("disc-r16-epoch3-validation", "dev adapter epoch 3"),
                    ("disc-r16-epoch2-holdout", "dev adapter epoch 2"),
                    ("disc-r16-epoch3-holdout", "dev adapter epoch 3"),
                    ("full-r16-epoch1-validation", "final adapter epoch 1"),
                    ("full-r16-epoch2-validation", "final adapter epoch 2 (chosen)"),
                    ("full-r16-epoch3-validation", "final adapter epoch 3")):
    p = gen / f"{name}.json"
    if not p.is_file():
        continue
    s = json.loads(p.read_text())["stats"]
    split = name.rsplit("-", 1)[1]
    lines.append(f"| {label} | {split} | {s['parsed']}/{s['n']} | {s['matched']} | {s['correct']} | "
                 f"{s['rescue']} | {s['harmful']} |")
lines += ["", "*harmful = v2 without LLM is correct, the LLM SQL matches the public example but is wrong on another "
          "instance (i.e. it would be accepted by a public-example check and lose the task).", ""]
OUT.write_text("\n".join(lines) + "\n")
print("\n".join(lines))
